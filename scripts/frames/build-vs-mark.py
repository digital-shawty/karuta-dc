#!/usr/bin/env python3
"""Draw the versus mark and write app/assets/cardgen/marks/vs-default.svg.

The letters are laid out on a pixel grid, their silhouette is traced into
closed polygons, and those are stroked with no fill. The result is a hollow
pixel-art VS: whatever it sits on shows through the letters, so it stays
legible over any background without needing a colour that suits them all.

Run with `npm run build:vs`. Edit the grids below to change the lettering.
"""

import pathlib

V = """
XXX....XXX
XXX....XXX
XXX....XXX
XXX....XXX
.XXX..XXX.
.XXX..XXX.
..XXXXXX..
..XXXXXX..
...XXXX...
...XXXX...
""".strip().split('\n')

S = """
XXXXXXXXXX
XXXXXXXXXX
XXX.......
XXX.......
XXXXXXXXXX
XXXXXXXXXX
.......XXX
.......XXX
XXXXXXXXXX
XXXXXXXXXX
""".strip().split('\n')

CELL = 10      # units per pixel
GAP = 2        # cells between the letters
STROKE = 6     # outline weight, in units

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGET = ROOT / 'app' / 'assets' / 'cardgen' / 'marks' / 'vs-default.svg'

def mask(rows, offset_x):
    return {(offset_x + x, y) for y, row in enumerate(rows)
            for x, ch in enumerate(row) if ch == 'X'}

def trace(cells):
    """Chain the boundary of a set of grid cells into closed loops.

    Every filled cell contributes the edges whose neighbour is empty, wound
    clockwise so they join head to tail. Holes come out as their own loop.
    """
    edges = {}
    for (x, y) in cells:
        if (x, y - 1) not in cells: edges[(x, y)] = (x + 1, y)
        if (x + 1, y) not in cells: edges[(x + 1, y)] = (x + 1, y + 1)
        if (x, y + 1) not in cells: edges[(x + 1, y + 1)] = (x, y + 1)
        if (x - 1, y) not in cells: edges[(x, y + 1)] = (x, y)

    loops = []
    while edges:
        start = next(iter(edges))
        loop, point = [start], edges.pop(start)
        while point != start:
            loop.append(point)
            point = edges.pop(point)
        # Drop points sitting part-way along a straight run.
        loops.append([p for i, p in enumerate(loop)
                      if (p[0] - loop[i-1][0], p[1] - loop[i-1][1])
                      != (loop[(i+1) % len(loop)][0] - p[0], loop[(i+1) % len(loop)][1] - p[1])])
    return loops

def main():
    cells = mask(V, 0) | mask(S, len(V[0]) + GAP)
    width = (len(V[0]) + GAP + len(S[0])) * CELL
    height = len(V) * CELL
    pad = STROKE

    paths = []
    for loop in trace(cells):
        points = [f'{x * CELL},{y * CELL}' for x, y in loop]
        paths.append('M ' + points[0] + ''.join(f' L {p}' for p in points[1:]) + ' Z')

    body = '\n'.join(f'    <path d="{p}"/>' for p in paths)
    TARGET.write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{-pad} {-pad} {width + pad * 2} {height + pad * 2}" width="{width + pad * 2}" height="{height + pad * 2}">
  <!--
    Generated by scripts/frames/build-vs-mark.py. Do not edit by hand.

    The versus mark: a pixel-art VS, outline only. There is no fill, so the
    letters are hollow and the matchup behind shows through them. That keeps
    the mark readable over any background without picking a colour that has to
    suit every one of them.

    `stroke` is the only colour the mark has. The resolver swaps it and sets
    the root width and height before rasterising, so a palette could be added
    later without touching these paths.

    Drawn rather than typeset: an SVG rendered into a canvas cannot fetch a
    font, so a <text> element would fall back to whatever the machine has.
  -->
  <g fill="none" stroke="#000000" stroke-width="{STROKE}"
     stroke-linejoin="miter" stroke-linecap="square" stroke-miterlimit="4">
{body}
  </g>
</svg>
''')
    print(f'{len(paths)} loops, {width + pad * 2} x {height + pad * 2} -> {TARGET.relative_to(ROOT)}')

if __name__ == '__main__':
    main()
